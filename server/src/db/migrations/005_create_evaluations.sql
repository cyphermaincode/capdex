CREATE TABLE IF NOT EXISTS evaluations (
  id SERIAL PRIMARY KEY,
  employee_id INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  evaluated_by INT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  cycle_date DATE NOT NULL,
  overall_score NUMERIC(5, 2) NOT NULL,
  status VARCHAR(50) DEFAULT 'SUBMITTED' CHECK (status IN ('DRAFT', 'SUBMITTED', 'ACKNOWLEDGED')),
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
