CREATE TABLE IF NOT EXISTS users (
  id SERIAL PRIMARY KEY,
  name VARCHAR(255) NOT NULL,
  email VARCHAR(255) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  role VARCHAR(50) NOT NULL CHECK (role IN ('HR', 'MANAGER', 'EMPLOYEE')),
  department_id INT REFERENCES departments(id) ON DELETE SET NULL,
  title VARCHAR(255),
  is_active BOOLEAN DEFAULT TRUE,
  is_laid_off BOOLEAN DEFAULT FALSE,
  layoff_reason TEXT,
  layoff_hr_notes TEXT,
  layoff_approved_at TIMESTAMP,
  layoff_proposed_by INT REFERENCES users(id) ON DELETE SET NULL,
  layoff_status VARCHAR(50) DEFAULT 'NONE' CHECK (layoff_status IN ('NONE', 'PENDING_APPROVAL', 'APPROVED', 'DECLINED')),
  is_on_pip BOOLEAN DEFAULT FALSE,
  pip_reason TEXT,
  pip_target_date DATE,
  pip_assigned_by INT REFERENCES users(id) ON DELETE SET NULL,
  pip_assigned_at TIMESTAMP,
  pip_status VARCHAR(50) DEFAULT 'NONE',
  demotion_status VARCHAR(50) DEFAULT 'NONE',
  demoted_title VARCHAR(255),
  demotion_reason TEXT,
  demotion_hr_notes TEXT,
  demotion_proposed_by INT REFERENCES users(id) ON DELETE SET NULL,
  phone VARCHAR(50),
  appraisal_date DATE,
  created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);
